test('Gantt keyboard move and resize preserve focus and persist', async ({authenticatedPage: page}, info) => {
	await page.goto(destination)
	const bar = page.getByRole('slider', {name: 'Task: Scheduled task', exact: true})
	await bar.focus()
	const moved = page.waitForRequest(request => /\/tasks\/1$/.test(request.url()) && request.method() === 'POST')
	await page.keyboard.press('ArrowRight')
	const move = (await moved).postDataJSON()
	expect(Date.parse(move.start_date)).toBe(Date.parse('2026-10-06T00:00:00Z')); expect(Date.parse(move.end_date)).toBe(Date.parse('2026-10-09T23:59:59.999Z'))
	await expect(bar).toHaveAttribute('aria-valuenow', String(Date.parse(move.start_date)))
	await expect(bar).toBeFocused()
	const resized = page.waitForRequest(request => /\/tasks\/1$/.test(request.url()) && request.method() === 'POST')
	await page.keyboard.press('Shift+ArrowRight')
	const resize = (await resized).postDataJSON()
	expect(resize.start_date).toBe(move.start_date); expect(Date.parse(resize.end_date)).toBe(Date.parse('2026-10-10T23:59:59.999Z'))
	await page.reload(); await expect(bar).toHaveAttribute('aria-valuenow', String(Date.parse(move.start_date)))
	await expect(bar).toHaveAttribute('aria-valuetext', /10\/10\/2026/)
	await info.attach('gantt-date-writes', {body: JSON.stringify([move, resize]), contentType: 'application/json'})
})
