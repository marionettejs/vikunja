test('Gantt pointer move and end resize publish whole-day changes', async ({authenticatedPage: page}) => {
	await page.goto(destination)
	const bar = page.getByRole('slider', {name: 'Task: Scheduled task', exact: true})
	await expect(bar).toBeVisible()
	const day = (await page.locator('.timeunit').first().boundingBox())!.width
	const rect = bar.locator('.gantt-bar'), box = (await rect.boundingBox())!
	const pending = page.waitForResponse(response => /\/tasks\/1$/.test(response.url()) && response.request().method() === 'POST')
	await page.mouse.move(box.x + box.width / 2, box.y + 16); await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + day, box.y + 16, {steps: 4}); await page.mouse.up()
	const moved = (await pending).request().postDataJSON()
	expect(Date.parse(moved.start_date)).toBe(Date.parse('2026-10-06T00:00:00Z'))
	await expect(bar).toHaveAttribute('aria-valuenow', String(Date.parse(moved.start_date)))
	const edge = (await bar.locator('.gantt-resize-right').boundingBox())!
	const resized = page.waitForResponse(response => /\/tasks\/1$/.test(response.url()) && response.request().method() === 'POST')
	await page.mouse.move(edge.x + edge.width / 2, edge.y + 16); await page.mouse.down(); await page.mouse.move(edge.x + edge.width / 2 + day, edge.y + 16, {steps: 4}); await page.mouse.up()
	expect(Date.parse((await resized).request().postDataJSON().end_date)).toBe(Date.parse('2026-10-10T23:59:59.999Z'))
	await page.reload(); await expect(bar).toHaveAttribute('aria-valuetext', /10\/10\/2026/)
})
