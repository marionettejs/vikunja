// Identical backend and outcomes for both shipped applications. These journeys
// deliberately use form labels and visible CSS, never native implementation IDs.
const save = page => page.getByRole('button', {name: 'Save', exact: true})
const response = (page, path: string, method: string) => page.waitForResponse(r => new URL(r.url()).pathname.endsWith(path) && r.request().method() === method)
async function headers(page) {return {Authorization: `Bearer ${await page.evaluate(() => localStorage.getItem('token'))}`}}
async function read(page, apiContext, path: string, authorization?: Record<string, string>) {const result = await apiContext.get(path, {headers: authorization ?? await headers(page)}); expect(result.ok()).toBe(true); return result.json()}
async function dismissInstall(page) {
 const banner = page.locator('.add-to-home-screen')
 if (await banner.isVisible()) await banner.getByRole('button', {name: 'Close banner', exact: true}).click()
}
async function creationFocus(page, name) {
 // Paired browser observations establish the rendered focus target. Modal
 // showModal overrides the earlier Vue directive on desktop too. Soft keeps
 // later CRUD evidence on failure without changing the case's pass criterion.
 await expect(name).toBeVisible()
 const target = page.viewportSize()!.width > 768 ? 'Close dialog' : 'Close'
 await expect.soft(page.getByRole('dialog').getByRole('button', {name: target, exact: true}).first()).toBeFocused()
}
async function capture(page, info, name: string) {
 await expect(page.locator('html')).toHaveClass(new RegExp(info.project.use.colorScheme))
 await page.evaluate(async () => {await document.fonts.ready})
 await info.attach(name, {body: await page.screenshot({fullPage: true, animations: 'disabled'}), contentType: 'image/png'})
 await info.attach(name + '-forms', {body: JSON.stringify(await page.locator('input, select, button, h1, h2').evaluateAll(elements => elements.filter(el => el.getBoundingClientRect().width).map(el => {
  const r = el.getBoundingClientRect(), s = getComputedStyle(el)
  const fieldLabels = 'labels' in el ? Array.from((el as HTMLInputElement).labels ?? [], label => label.textContent?.trim()).join(' ') : ''
  return {tag: el.tagName, label: fieldLabels || el.getAttribute('aria-label') || el.textContent?.trim(), id: el.id, rect: {x: r.x, y: r.y, width: r.width, height: r.height}, font: s.font, color: s.color, background: s.backgroundColor}
 })), null, 2), contentType: 'application/json'})
}
