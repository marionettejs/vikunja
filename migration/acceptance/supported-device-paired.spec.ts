test('password share create anonymous rejection authentication reload and revocation', async ({authenticatedPage: page, apiContext, browser}, info) => {
 await ProjectFactory.create(1, {title: 'Device shared project'}); await createDefaultViews(1)
 await TaskFactory.create(1, {title: 'Device shared task'})
 await page.goto('/projects'); await expect(page.locator('.project-grid')).toContainText('Device shared project')
 await dismissInstall(page)
 await page.goto('/projects/1/settings/share')
 const links = page.getByRole('heading', {name: /^Share Links/}).locator('..')
 await links.getByRole('button', {name: 'Create a link share', exact: true}).click()
 await page.getByLabel('Name (optional)', {exact: true}).fill('Device password link')
 await page.getByLabel('Password (optional)', {exact: true}).fill('device-share-password')
 const created = response(page, '/projects/1/shares', 'PUT'); await links.getByRole('button', {name: 'Share', exact: true}).click(); expect((await created).ok()).toBe(true)
 const shares = await read(page, apiContext, 'projects/1/shares'); expect(shares).toHaveLength(1)
 expect(shares[0]).toMatchObject({name: 'Device password link', permission: 0, sharing_type: 2})
 await capture(page, info, 'share-created')
 const anonymous = await browser.newContext({baseURL: info.project.use.baseURL, viewport: page.viewportSize()!, colorScheme: info.project.use.colorScheme, locale: 'en-US', timezoneId: 'UTC', serviceWorkers: 'block'})
 try {
  const visitor = await anonymous.newPage(); await setupApiUrl(visitor)
  await visitor.goto(`/share/${shares[0].hash}/auth`)
  const password = visitor.locator('#linkSharePassword'); await password.fill('wrong-password'); await password.press('Enter')
  await expect(visitor.getByText('The password is invalid.', {exact: true})).toBeVisible(); await expect(password).toHaveValue('wrong-password')
  await capture(visitor, info, 'share-password-rejected')
  await password.fill('device-share-password'); await password.press('Enter')
  await expect(visitor.locator('.tasks')).toContainText('Device shared task')
  expect(await visitor.evaluate(() => localStorage.getItem('token'))).toBeNull()
  await expect(visitor.getByPlaceholder('Add a task…')).toHaveCount(0)
  const challenge = response(visitor, `/shares/${shares[0].hash}/auth`, 'POST')
  await visitor.reload(); expect((await challenge).status()).toBe(412)
  await expect(password).toBeVisible(); await expect(visitor.locator('.tasks')).toHaveCount(0)
  await capture(visitor, info, 'anonymous-share-reload-password-challenge')
  await password.fill('device-share-password')
  const reauthenticated = response(visitor, `/shares/${shares[0].hash}/auth`, 'POST'); await password.press('Enter'); expect((await reauthenticated).ok()).toBe(true)
  await expect(visitor.locator('.tasks')).toContainText('Device shared task'); await capture(visitor, info, 'anonymous-share-reloaded')
  await links.getByRole('button', {name: 'Remove a link share', exact: true}).click()
  await page.getByRole('button', {name: 'Do it!', exact: true}).click()
  await expect.poll(async () => (await read(page, apiContext, 'projects/1/shares')).length).toBe(0)
  expect((await apiContext.post(`shares/${shares[0].hash}/auth`, {data: {password: 'device-share-password'}})).ok()).toBe(false)
  const denied = response(visitor, `/shares/${shares[0].hash}/auth`, 'POST')
  await visitor.goto(`/share/${shares[0].hash}/auth`)
  const deniedResponse = await denied; expect(deniedResponse.ok()).toBe(false)
  const denial = await deniedResponse.json(); expect(typeof denial.message).toBe('string')
  await expect(visitor.getByText(denial.message, {exact: false})).toBeVisible()
  await expect(visitor.locator('.tasks')).toHaveCount(0)
  await capture(visitor, info, 'anonymous-share-revoked')
 } finally {await anonymous.close()}
})
